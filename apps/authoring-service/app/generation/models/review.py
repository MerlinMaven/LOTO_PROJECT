"""
ReviewableField — generic wrapper for every HSE-reviewer-visible field.

Every value the generation pipeline produces is wrapped in ReviewableField[T].
This allows the HSE dashboard to:
  - Display the AI-generated value alongside its confidence score
  - Let the reviewer edit the value without losing the original
  - Track approval status per field, not just per procedure
  - Attach review notes to specific fields
"""

from __future__ import annotations

from datetime import datetime
from app.compat import StrEnum
from typing import Generic, Optional, TypeVar

from pydantic import BaseModel, Field

T = TypeVar("T")


class ReviewStatus(StrEnum):
    PENDING       = "pending"        # Not yet reviewed
    APPROVED      = "approved"       # Reviewer accepted as-is
    EDITED        = "edited"         # Reviewer provided a replacement value
    REJECTED      = "rejected"       # Reviewer flagged this as wrong/unsafe


class ReviewableField(BaseModel, Generic[T]):
    """
    Wraps any generated value with provenance and review state.

    Usage:
        label: ReviewableField[str] = ReviewableField(
            generated_value="Main Power Switch",
            confidence_score=0.95,
        )

    The dashboard reads `effective_value` which returns the edited value
    if the reviewer provided one, otherwise the generated value.
    """
    generated_value: T = Field(
        ...,
        description="Value as generated by the AI pipeline.",
    )
    confidence_score: float = Field(
        ge=0.0,
        le=1.0,
        description="AI confidence in this generated value (0.0–1.0).",
    )
    edited_value: Optional[T] = Field(
        None,
        description="Reviewer-provided replacement. Overrides generated_value when set.",
    )
    status: ReviewStatus = Field(
        ReviewStatus.PENDING,
        description="Current review state for this field.",
    )
    review_notes: Optional[str] = Field(
        None,
        description="Free-text comment from the reviewer.",
    )
    reviewed_by: Optional[str] = Field(
        None,
        description="Identifier of the HSE reviewer who last touched this field.",
    )
    reviewed_at: Optional[datetime] = Field(
        None,
        description="UTC timestamp of last review action.",
    )

    @property
    def effective_value(self) -> T:
        """The value to use: edited if provided, otherwise generated."""
        return self.edited_value if self.edited_value is not None else self.generated_value

    @property
    def needs_review(self) -> bool:
        """True when confidence is low and the field has not been reviewed yet."""
        return self.status == ReviewStatus.PENDING and self.confidence_score < 0.75

    @property
    def is_finalized(self) -> bool:
        """True when the reviewer has taken an explicit action on this field."""
        return self.status in (ReviewStatus.APPROVED, ReviewStatus.EDITED)

    @classmethod
    def from_value(cls, value: T, confidence: float = 1.0) -> "ReviewableField[T]":
        """Convenience constructor for high-confidence values."""
        return cls(generated_value=value, confidence_score=confidence)
